const { z } = require('zod');

const registerSchema = z.object({
  email: z.string().email('Invalid email address'),
  username: z
    .string()
    .min(3, 'Username must be at least 3 characters')
    .max(30, 'Username must be at most 30 characters')
    .regex(/^[a-z0-9][a-z0-9-]*[a-z0-9]$/, 'Username must be lowercase alphanumeric with hyphens only')
    .transform((val) => val.toLowerCase()),
  password: z.string().min(8, 'Password must be at least 8 characters'),
});

const loginSchema = z.object({
  email: z.string().email('Invalid email address'),
  password: z.string().min(1, 'Password is required'),
});

const forgotPasswordSchema = z.object({
  email: z.string().email('Invalid email address'),
});

const resetPasswordSchema = z.object({
  token: z.string().min(1, 'Reset token is required'),
  password: z.string().min(8, 'Password must be at least 8 characters'),
});

// ─── TOTP two-factor ─────────────────────────────────────

// Base32 as generated by otplib (RFC 4648 alphabet, unpadded)
const base32SecretSchema = z
  .string()
  .min(16, 'Secret is required')
  .max(128, 'Secret is too long')
  .regex(/^[A-Z2-7]+=*$/, 'Invalid secret format');

const verifyTotpSchema = z.object({
  token: z.string().regex(/^\d{6}$/, 'Verification code must be exactly 6 digits'),
  secret: base32SecretSchema,
});

// Password is optional so OAuth-only accounts can disable with confirm:true;
// the service still enforces a password check for password accounts.
const disableTotpSchema = z.object({
  password: z.string().min(1, 'Password is required').optional(),
  confirm: z.boolean().optional(),
});

const totpChallengeSchema = z.object({
  tempToken: z.string().min(1, 'Temporary token is required'),
  totpCode: z
    .string()
    .min(6, 'Code must be at least 6 characters')
    .max(12, 'Code must be at most 12 characters')
    .transform((val) => val.replace(/[\s-]/g, '').toLowerCase()),
});

module.exports = {
  registerSchema,
  loginSchema,
  forgotPasswordSchema,
  resetPasswordSchema,
  verifyTotpSchema,
  disableTotpSchema,
  totpChallengeSchema,
};
